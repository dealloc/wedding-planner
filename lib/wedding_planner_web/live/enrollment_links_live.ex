defmodule WeddingPlannerWeb.Live.EnrollmentLinksLive do
  @moduledoc """
  The enrollment link generation screen (AUTH-04 through AUTH-07,
  `.claude/design/ui-decisions.md` §3, point 4): create a device link for the signed-in
  user's own account, or an invitation link for a brand-new user (DR-20: the invitee
  picks their own display name later, on `WeddingPlannerWeb.Live.EnrollmentLive`, so
  nothing is asked here beyond which flavour to create); see every still-usable link as a
  card with its URL and QR code shown together (never toggled) and its expiry stated; and
  revoke any of them.

  Every flavour that exists is listed here, not only ones the current user issued —
  AUTH-07 lets *any* signed-in user revoke *any* unused link, so a recovery link
  generated by the release command (task 18, not built yet) will show up here too, once
  it exists, with no change needed on this screen.

  Card actions are optimistic against the in-memory stream (`stream_insert`/
  `stream_delete`) but every state change is still re-derived from the database on the
  next full list fetch — there is no cached staleness beyond one LiveView process's own
  lifetime.
  """
  use WeddingPlannerWeb, :live_view

  on_mount {WeddingPlannerWeb.Live.TimeZoneHook, :default}

  alias WeddingPlanner.Accounts.EnrollmentLinks
  alias WeddingPlanner.Accounts.EnrollmentQr
  alias WeddingPlanner.Log
  alias WeddingPlanner.Repo
  alias WeddingPlannerWeb.Format
  alias WeddingPlannerWeb.Live.TimeZoneHook

  @impl true
  def mount(_params, _session, socket) do
    socket =
      socket
      |> assign(:page_title, "Enrollment links")
      |> stream(:links, EnrollmentLinks.list_active_links())

    {:ok, socket}
  end

  @impl true
  def handle_event("create_device_link", _params, socket) do
    create_link(socket, &EnrollmentLinks.create_device_link/1, "created")
  end

  @impl true
  def handle_event("create_invitation_link", _params, socket) do
    create_link(socket, &EnrollmentLinks.create_invitation_link/1, "created")
  end

  @impl true
  def handle_event("revoke", %{"id" => id}, socket) do
    %{current_scope: scope} = socket.assigns
    now = DateTime.utc_now() |> DateTime.truncate(:second)

    case id |> String.to_integer() |> EnrollmentLinks.get_link() do
      nil ->
        {:noreply, socket}

      link ->
        case EnrollmentLinks.revoke(link, now) do
          {:ok, revoked} ->
            Log.entry(
              scope,
              {:enrollment_link, revoked.id},
              log_description(scope.user, revoked, "revoked")
            )

            {:noreply, stream_delete(socket, :links, link)}

          {:error, _reason} ->
            socket =
              socket
              |> put_flash(:error, "This link can no longer be revoked.")
              |> stream_delete(:links, link)

            {:noreply, socket}
        end
    end
  end

  defp create_link(socket, create_fun, verb) do
    %{current_scope: scope} = socket.assigns

    case create_fun.(scope.user) do
      {:ok, link} ->
        link = Repo.preload(link, [:issuing_user, :target_user])
        Log.entry(scope, {:enrollment_link, link.id}, log_description(scope.user, link, verb))
        {:noreply, stream_insert(socket, :links, link, at: 0)}

      {:error, _changeset} ->
        {:noreply, put_flash(socket, :error, "Could not create the link. Please try again.")}
    end
  end

  # "Wannes created a device enrollment link" / "Wannes revoked an invitation enrollment
  # link" (AUTH-11, XC-10 style).
  defp log_description(user, link, verb) do
    label = EnrollmentLinks.flavour_label(link)
    article = if label == "invitation", do: "an", else: "a"
    "#{user.display_name} #{verb} #{article} #{label} enrollment link"
  end

  defp target_summary(%{flavour: "device", target_user: user}), do: "For #{user.display_name}"

  defp target_summary(%{flavour: "user_invitation", target_user: nil}),
    do: "For a new user — not yet claimed"

  defp target_summary(%{flavour: "recovery", target_user: user}),
    do: "Recovery link for #{user.display_name}"

  @impl true
  def render(assigns) do
    ~H"""
    <Layouts.app flash={@flash} current_scope={@current_scope}>
      <TimeZoneHook.probe id="enrollment-links-time-zone-probe" />

      <.header>
        Enrollment links
        <:subtitle>
          Add this account to another device, or invite someone new. Every link is
          single-use and expires in 15 minutes.
        </:subtitle>
      </.header>

      <div class="flex flex-wrap gap-3">
        <.button
          variant="primary"
          id="create-device-link-button"
          phx-click="create_device_link"
        >
          Add this account to a new device
        </.button>
        <.button
          variant="secondary"
          id="create-invitation-link-button"
          phx-click="create_invitation_link"
        >
          Invite a new user
        </.button>
      </div>

      <div id="enrollment-links" phx-update="stream" class="mt-6 flex flex-col gap-4">
        <p
          id="enrollment-links-empty"
          class="hidden only:block rounded-field border border-dashed border-line-strong p-6 text-center text-sm text-ink-soft"
        >
          No active enrollment links right now.
        </p>

        <div
          :for={{id, link} <- @streams.links}
          id={id}
          class="flex flex-col gap-4 rounded-field border border-line bg-surface-raised p-4 sm:flex-row sm:items-center sm:justify-between"
        >
          <div class="flex flex-col gap-3 sm:flex-row sm:items-center sm:gap-4">
            <div
              class="shrink-0 rounded-field border border-line bg-white p-2"
              title="Scan to open the enrollment link"
            >
              {Phoenix.HTML.raw(EnrollmentQr.svg(link_url(link)))}
            </div>

            <div class="min-w-0">
              <p class="text-sm font-semibold text-ink">{target_summary(link)}</p>
              <input
                type="text"
                readonly
                id={"#{id}-url"}
                value={link_url(link)}
                onclick="this.select()"
                class="mt-1 w-full max-w-sm rounded-field border border-line-strong bg-surface px-2 py-1.5 font-mono text-xs text-ink-soft"
              />
              <p class="mt-1 text-xs text-ink-faint">
                Expires {Format.datetime(link.expires_at, @time_zone)}
              </p>
            </div>
          </div>

          <.button
            variant="destructive"
            id={"#{id}-revoke"}
            phx-click="revoke"
            phx-value-id={link.id}
            data-confirm="Revoke this enrollment link? It can no longer be opened afterwards."
          >
            Revoke
          </.button>
        </div>
      </div>
    </Layouts.app>
    """
  end

  defp link_url(link), do: url(~p"/enroll/#{link.token}")
end
