defmodule WeddingPlannerWeb.Live.EnrollmentLive do
  @moduledoc """
  The public enrollment landing page (`AUTH-01`, `AUTH-04` through `AUTH-09`), reached at
  `/enroll/:token`. All three flavours converge here (`.claude/design/ui-decisions.md`
  §3, point 5):

    * **device** — registers an additional passkey for the issuing user, who does not
      need to be signed in on the device opening the link. Silent: a "Register passkey"
      button, no extra fields.
    * **user_invitation** — creates a brand-new user. `DR-20` supersedes AUTH-05's "name
      chosen at creation" wording: the invitee picks their own display name **here**, not
      on the generation screen — the link itself carries no name.
    * **recovery** — generated by an operator release command for an existing user who
      lost every device (`AUTH-09`, task 18, not built by this task). Behaves exactly
      like a device link for its target user, with reassurance copy instead of the
      "additional passkey" framing.

  No passkey-name field is asked here (per the locked flow) — every passkey registered
  through this page is named `"New passkey"`; `AUTH-08`'s rename is a later screen.

  ## Single-use, made atomic (`AUTH-06`)

  A link is looked up and validated on `mount/3` (`WeddingPlanner.Accounts.EnrollmentLinks.
  fetch_for_redemption/2`), but that is only ever a *read* — it is not what makes the link
  single-use, since two devices could both pass it for the same link at the same moment.
  The link is only actually consumed once a real ceremony **succeeds**:
  `WebAuthn.finish_registration/4` returns `{:ok, passkey}` and then
  `EnrollmentLinks.claim/2`'s atomic `UPDATE ... WHERE used_at IS NULL` wins. If `claim/2`
  loses that race (someone else's ceremony finished first), this process rolls back what
  it just created — deletes the passkey it just persisted, and for a user-invitation link,
  the provisional user too — and shows the same "already used" state a late-arriving
  visitor to a genuinely stale link would see. See `EnrollmentLinks`' moduledoc for why the
  `UPDATE` itself needs no explicit transaction.

  ## The provisional user (`DR-22`, user-invitation only)

  Exactly the same shape as `WeddingPlannerWeb.Live.SetupLive`'s bootstrap ceremony,
  because it is the same problem: the WebAuthn user handle is `users.id`, so the row must
  exist *before* `begin_registration/1` can run. A user-invitation link creates the user
  the moment a name is submitted, then starts the ceremony against it:

    * **cancel / client error / unsupported browser / a `finish_registration` failure, or
      losing the single-use race** (all handled here, in this process, while it is still
      alive) — this LiveView deletes the provisional user itself and tells the guard to
      stand down.
    * **this LiveView process dies first** (tab closed, navigated away, crashed) —
      `WeddingPlanner.Accounts.SetupGuard`, reused unmodified (its API is already generic:
      an owner pid plus a user id, nothing setup-specific), deletes it instead.

  Device and recovery links have no provisional user — their target user already exists —
  so no guard is started for those flavours.

  Nothing is written to the activity log (`AUTH-11`) until `finish_registration/4` actually
  returns `{:ok, passkey}` **and** this process wins the `claim/2` race — logging any
  earlier could reference a user or passkey that ends up rolled back.
  """
  use WeddingPlannerWeb, :live_view

  alias WeddingPlanner.Accounts.EnrollmentLinks
  alias WeddingPlanner.Accounts.Scope
  alias WeddingPlanner.Accounts.SetupGuard
  alias WeddingPlanner.Accounts.User
  alias WeddingPlanner.Accounts.WebAuthn
  alias WeddingPlanner.Log
  alias WeddingPlanner.Repo
  alias WeddingPlannerWeb.Live.PasskeyCeremony

  @passkey_name "New passkey"

  @invalid_messages %{
    not_found: "This enrollment link is invalid.",
    used: "This enrollment link has already been used.",
    expired: "This enrollment link has expired.",
    revoked: "This enrollment link has been revoked."
  }

  @impl true
  def mount(%{"token" => token}, _session, socket) do
    socket =
      socket
      |> assign(:page_title, "Enrollment")
      |> assign(:token, token)
      |> assign(:challenge, nil)
      |> assign(:setup_guard, nil)
      |> assign(:target_user, nil)
      |> assign(:display_name, nil)

    socket =
      case EnrollmentLinks.fetch_for_redemption(token) do
        {:ok, link} -> mount_link(socket, link)
        {:error, reason} -> mount_invalid(socket, reason)
      end

    {:ok, socket}
  end

  defp mount_link(socket, %{flavour: "user_invitation"} = link) do
    socket
    |> assign(:link, link)
    |> assign(:state, :name_form)
    |> assign(:form, to_form(%{"display_name" => ""}, as: :invitation))
  end

  defp mount_link(socket, link) do
    socket
    |> assign(:link, link)
    |> assign(:state, :ready)
    |> assign(:target_user, link.target_user)
  end

  defp mount_invalid(socket, reason) do
    socket
    |> assign(:link, nil)
    |> assign(:state, :invalid)
    |> assign(:invalid_reason, reason)
  end

  @impl true
  def handle_event("submit_name", %{"invitation" => %{"display_name" => name}}, socket) do
    if socket.assigns.state == :name_form do
      submit_name(socket, name)
    else
      {:noreply, socket}
    end
  end

  @impl true
  def handle_event("register_passkey", _params, socket) do
    if socket.assigns.state == :ready do
      {:noreply, start_ceremony(socket, socket.assigns.target_user)}
    else
      {:noreply, socket}
    end
  end

  @impl true
  def handle_event("passkey:registration-success", params, socket) do
    if socket.assigns.state == :ceremony do
      {:noreply, finish_ceremony(socket, params)}
    else
      {:noreply, socket}
    end
  end

  @impl true
  def handle_event("passkey:cancelled", _params, socket) do
    if socket.assigns.state == :ceremony do
      {:noreply, abort_ceremony(socket, nil)}
    else
      {:noreply, socket}
    end
  end

  @impl true
  def handle_event("passkey:error", %{"message" => message}, socket) do
    if socket.assigns.state == :ceremony do
      {:noreply, abort_ceremony(socket, message)}
    else
      {:noreply, socket}
    end
  end

  @impl true
  def handle_event("passkey:unsupported", _params, socket) do
    # Fires on every mount where the ceremony hook is rendered (:name_form, :ready,
    # :ceremony), and again defensively mid-ceremony — a no-op outside those states (in
    # particular :invalid, where there is no `@link` to read a flavour from, and
    # :completed, where the link is already used and must not be reopened).
    if socket.assigns.state in [:name_form, :ready, :ceremony] do
      {:noreply, abort_ceremony(socket, "This browser does not support passkeys.")}
    else
      {:noreply, socket}
    end
  end

  defp submit_name(socket, name) do
    case %User{} |> User.changeset(%{"display_name" => name}) |> Repo.insert() do
      {:ok, user} ->
        {:noreply, start_ceremony(assign(socket, :display_name, user.display_name), user)}

      {:error, changeset} ->
        {:noreply, assign(socket, :form, to_form(changeset, as: :invitation))}
    end
  end

  defp start_ceremony(socket, %User{} = user) do
    {challenge, options} = WebAuthn.begin_registration(user)

    socket =
      socket
      |> assign(:state, :ceremony)
      |> assign(:target_user, user)
      |> assign(:challenge, challenge)
      |> push_event("passkey:create", options)

    if socket.assigns.link.flavour == "user_invitation" do
      {:ok, guard} = SetupGuard.start(owner: self(), user_id: user.id)
      assign(socket, :setup_guard, guard)
    else
      socket
    end
  end

  defp finish_ceremony(socket, params) do
    %{target_user: user, challenge: challenge} = socket.assigns

    case WebAuthn.finish_registration(user, challenge, params, name: @passkey_name) do
      {:ok, passkey} ->
        claim_and_complete(socket, passkey)

      {:error, _reason} ->
        abort_ceremony(socket, "Passkey registration failed. Please try again.")
    end
  end

  defp claim_and_complete(socket, passkey) do
    %{link: link, target_user: user} = socket.assigns
    now = DateTime.utc_now() |> DateTime.truncate(:second)

    case EnrollmentLinks.claim(link, now) do
      :ok ->
        if link.flavour == "user_invitation" do
          {:ok, _link} = EnrollmentLinks.assign_target_user(link, user)
          SetupGuard.disarm(socket.assigns.setup_guard)
        end

        Log.entry(
          Scope.for_user(user),
          {:passkey, passkey.id},
          "#{user.display_name} registered passkey '#{passkey.name}'"
        )

        socket
        |> assign(:state, :completed)
        |> assign(:challenge, nil)
        |> assign(:setup_guard, nil)

      :error ->
        # Lost the single-use race: someone else's ceremony claimed this link first.
        # Roll back exactly what this attempt just created, then show the same
        # "already used" state a late visitor to a genuinely stale link would see.
        Repo.delete(passkey)

        if link.flavour == "user_invitation" do
          Repo.delete(user)
          SetupGuard.disarm(socket.assigns.setup_guard)
        end

        socket
        |> assign(:state, :invalid)
        |> assign(:invalid_reason, :used)
        |> assign(:challenge, nil)
        |> assign(:setup_guard, nil)
        |> assign(:target_user, nil)
    end
  end

  # Ends an in-progress (or not-yet-started) ceremony: for a user-invitation link,
  # deletes the provisional user (if any) and tells the guard to stand down, returning
  # to the name form with the display name kept so it doesn't have to be retyped; for a
  # device or recovery link, there is nothing to clean up, so it just returns to :ready.
  defp abort_ceremony(socket, flash_message) do
    %{link: link, target_user: target_user, setup_guard: guard} = socket.assigns

    socket =
      case link.flavour do
        "user_invitation" ->
          if target_user, do: Repo.delete(target_user)
          if guard, do: SetupGuard.disarm(guard)

          socket
          |> assign(:state, :name_form)
          |> assign(:target_user, nil)
          |> assign(
            :form,
            to_form(%{"display_name" => socket.assigns.display_name || ""}, as: :invitation)
          )

        _ ->
          assign(socket, :state, :ready)
      end

    socket =
      socket
      |> assign(:challenge, nil)
      |> assign(:setup_guard, nil)

    if flash_message, do: put_flash(socket, :error, flash_message), else: socket
  end

  @impl true
  def render(%{state: :invalid} = assigns) do
    assigns = assign(assigns, :message, Map.fetch!(@invalid_messages, assigns.invalid_reason))

    ~H"""
    <Layouts.app flash={@flash}>
      <div
        id="enrollment-invalid"
        class="mx-auto max-w-md rounded-field border border-line bg-surface-raised p-6 text-center"
      >
        <.icon name="hero-exclamation-triangle" class="mx-auto size-8 text-bad" />
        <h1 class="mt-2 text-lg font-semibold text-ink">This link can't be used</h1>
        <p class="mt-2 text-sm text-ink-soft">{@message}</p>
      </div>
    </Layouts.app>
    """
  end

  def render(%{state: :name_form} = assigns) do
    ~H"""
    <Layouts.app flash={@flash}>
      <div
        id="enrollment-name-form-card"
        class="mx-auto max-w-md rounded-field border border-line bg-surface-raised p-6"
      >
        <h1 class="text-lg font-semibold text-ink">You've been invited</h1>
        <p class="mt-1 text-sm text-ink-soft">
          {@link.issuing_user.display_name} invited you to join Wedding Planner. Choose the
          name you'll be shown as, then register a passkey on this device.
        </p>

        <.form
          for={@form}
          id="enrollment-name-form"
          phx-submit="submit_name"
          class="mt-4 flex flex-col gap-4"
        >
          <.input field={@form[:display_name]} type="text" label="Your name" />

          <button
            type="submit"
            id="enrollment-name-submit"
            class="mt-2 inline-flex min-h-11 items-center justify-center rounded-field bg-accent px-4 text-sm font-semibold text-white shadow-sm transition-all duration-150 ease-out hover:opacity-90 active:scale-[0.98] cursor-pointer"
          >
            Continue
          </button>
        </.form>
      </div>

      <PasskeyCeremony.ceremony id="enrollment-passkey-ceremony" />
    </Layouts.app>
    """
  end

  def render(%{state: :ready, link: %{flavour: "recovery"}} = assigns) do
    ~H"""
    <Layouts.app flash={@flash}>
      <div
        id="enrollment-ready-card"
        class="mx-auto max-w-md rounded-field border border-line bg-surface-raised p-6 text-center"
      >
        <h1 class="text-lg font-semibold text-ink">Account recovery</h1>
        <p class="mt-2 text-sm text-ink-soft">
          This will register a new passkey for <strong>{@target_user.display_name}</strong>.
          If you didn't request this, you can safely close this page — nothing happens
          until you press the button below.
        </p>
        <button
          type="button"
          id="enrollment-register-button"
          phx-click="register_passkey"
          class="mt-4 inline-flex min-h-11 items-center justify-center rounded-field bg-accent px-4 text-sm font-semibold text-white shadow-sm transition-all duration-150 ease-out hover:opacity-90 active:scale-[0.98] cursor-pointer"
        >
          Register passkey
        </button>
      </div>

      <PasskeyCeremony.ceremony id="enrollment-passkey-ceremony" />
    </Layouts.app>
    """
  end

  def render(%{state: :ready} = assigns) do
    ~H"""
    <Layouts.app flash={@flash}>
      <div
        id="enrollment-ready-card"
        class="mx-auto max-w-md rounded-field border border-line bg-surface-raised p-6 text-center"
      >
        <h1 class="text-lg font-semibold text-ink">Add this device</h1>
        <p class="mt-2 text-sm text-ink-soft">
          Register an additional passkey for <strong>{@target_user.display_name}</strong>.
        </p>
        <button
          type="button"
          id="enrollment-register-button"
          phx-click="register_passkey"
          class="mt-4 inline-flex min-h-11 items-center justify-center rounded-field bg-accent px-4 text-sm font-semibold text-white shadow-sm transition-all duration-150 ease-out hover:opacity-90 active:scale-[0.98] cursor-pointer"
        >
          Register passkey
        </button>
      </div>

      <PasskeyCeremony.ceremony id="enrollment-passkey-ceremony" />
    </Layouts.app>
    """
  end

  def render(%{state: :ceremony} = assigns) do
    ~H"""
    <Layouts.app flash={@flash}>
      <div
        id="enrollment-ceremony-card"
        class="mx-auto max-w-md rounded-field border border-line bg-surface-raised p-6 text-center"
      >
        <h1 class="text-lg font-semibold text-ink">Follow your browser's prompt</h1>
        <p class="mt-2 text-sm text-ink-soft">
          Registering a passkey for {@target_user.display_name}&hellip;
        </p>
      </div>

      <PasskeyCeremony.ceremony id="enrollment-passkey-ceremony" />
    </Layouts.app>
    """
  end

  def render(%{state: :completed} = assigns) do
    ~H"""
    <Layouts.app flash={@flash}>
      <div
        id="enrollment-completed"
        class="mx-auto max-w-md rounded-field border border-line bg-surface-raised p-6 text-center"
      >
        <.icon name="hero-check-circle" class="mx-auto size-8 text-good" />
        <h1 class="mt-2 text-lg font-semibold text-ink">
          You're all set, {@target_user.display_name}
        </h1>
        <p class="mt-2 text-sm text-ink-soft">A passkey is registered on this device.</p>
        <.link
          navigate={~p"/login"}
          id="enrollment-completed-sign-in"
          class="mt-4 inline-flex min-h-11 items-center justify-center rounded-field bg-accent px-4 text-sm font-semibold text-white shadow-sm transition-all duration-150 ease-out hover:opacity-90 active:scale-[0.98]"
        >
          Sign in
        </.link>
      </div>
    </Layouts.app>
    """
  end
end
