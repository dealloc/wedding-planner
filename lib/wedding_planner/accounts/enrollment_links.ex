defmodule WeddingPlanner.Accounts.EnrollmentLinks do
  @moduledoc """
  Enrollment link generation, lookup and revocation (AUTH-04 through AUTH-09) — the
  context sitting above `WeddingPlanner.Accounts.EnrollmentLink`'s changesets.

  `WeddingPlannerWeb.Live.EnrollmentLinksLive` (device/invitation generation,
  authenticated), `WeddingPlanner.Accounts.Recovery` (recovery generation, AUTH-09, run outside any
  request) and `WeddingPlannerWeb.Live.EnrollmentLive` (the public landing page at
  `/enroll/:token`) are the only callers; each writes its own AUTH-11 log entry, since
  only the caller knows who — or what, for the operator command — is acting and what
  happened.

  ## Single-use, made atomic (AUTH-06)

  A link is consumed only once its registration ceremony actually *succeeds* — not when
  the landing page is opened, and not merely when a ceremony starts. A cancelled or
  failed attempt must leave the link usable until it expires. `claim/2` is the one place
  that flips `used_at`, and it does so with a single

      UPDATE enrollment_links SET used_at = ?
      WHERE id = ? AND used_at IS NULL AND revoked_at IS NULL AND expires_at > ?

  rather than a read-then-write. SQLite serializes writes onto one connection, so two
  concurrent `claim/2` calls for the same link are themselves serialized by the database;
  by the time the second one runs, `used_at` is no longer `NULL`, so its `WHERE` clause
  matches zero rows. No explicit transaction is needed — a single `UPDATE` statement is
  already atomic, the same guarantee `WeddingPlanner.Accounts.Setup.create_first_user/1`
  gets from wrapping a read-then-write in `mode: :immediate` instead.

  `WeddingPlannerWeb.Live.EnrollmentLive` only ever calls `claim/2` *after*
  `WeddingPlanner.Accounts.WebAuthn.finish_registration/4` has already returned
  `{:ok, passkey}` for a real ceremony. If `claim/2` then reports `:error` (this caller
  lost the race), it is responsible for rolling back what it just created — the passkey,
  and for a user-invitation link, the provisional user too — see that module's moduledoc
  for the full per-outcome cleanup story (`DR-22`).
  """

  import Ecto.Query, only: [from: 2]

  alias WeddingPlanner.Accounts.EnrollmentLink
  alias WeddingPlanner.Accounts.User
  alias WeddingPlanner.Repo

  @type redemption_error :: :not_found | :used | :expired | :revoked

  @doc "AUTH-04: creates a device link issued by, and targeting, `user`."
  @spec create_device_link(User.t()) :: {:ok, EnrollmentLink.t()} | {:error, Ecto.Changeset.t()}
  def create_device_link(%User{} = user) do
    user |> EnrollmentLink.device_link_changeset() |> Repo.insert()
  end

  @doc "AUTH-05: creates a user-invitation link issued by `user`, with no target user yet."
  @spec create_invitation_link(User.t()) ::
          {:ok, EnrollmentLink.t()} | {:error, Ecto.Changeset.t()}
  def create_invitation_link(%User{} = user) do
    user |> EnrollmentLink.user_invitation_link_changeset() |> Repo.insert()
  end

  # AUTH-06 fixes 15 minutes as *the* enrollment link default, but a recovery link's
  # output has to reach the target user out of band (a phone call, a text message)
  # before they can even open it, on top of whatever time it then takes them to find a
  # working device — 15 minutes is tight for that chain. AUTH-09 doesn't fix a value
  # itself, so this command widens it rather than silently inheriting a default sized
  # for the other two flavours, which are opened by the same person, on the same
  # screen, moments after being generated.
  @recovery_ttl_seconds 60 * 60

  @doc """
  AUTH-09: creates a recovery link for `user`, generated by an operator release command
  with no issuing user. Expiry is widened to #{div(@recovery_ttl_seconds, 60)} minutes
  (see the module attribute above) rather than AUTH-06's general 15-minute default.
  """
  @spec create_recovery_link(User.t()) :: {:ok, EnrollmentLink.t()} | {:error, Ecto.Changeset.t()}
  def create_recovery_link(%User{} = user) do
    expires_at =
      DateTime.utc_now()
      |> DateTime.add(@recovery_ttl_seconds, :second)
      |> DateTime.truncate(:second)

    user
    |> EnrollmentLink.recovery_link_changeset(%{expires_at: expires_at})
    |> Repo.insert()
  end

  @doc "Fetches a link by its primary key, or `nil` if it doesn't exist."
  @spec get_link(pos_integer()) :: EnrollmentLink.t() | nil
  def get_link(id), do: Repo.get(EnrollmentLink, id)

  @doc """
  Lists every link that is still usable right now — not used, not revoked, not past its
  expiry — newest first, with `:issuing_user` and `:target_user` preloaded for display.

  Every flavour is included: AUTH-07 lets any user revoke any unused link, not only ones
  they issued, so a recovery link generated by the release command (task 18) will show up
  here too once that command exists, with no change needed on this end.
  """
  @spec list_active_links(DateTime.t()) :: [EnrollmentLink.t()]
  def list_active_links(now \\ DateTime.utc_now()) do
    Repo.all(
      from l in EnrollmentLink,
        where: is_nil(l.used_at) and is_nil(l.revoked_at) and l.expires_at > ^now,
        # `inserted_at` has only second resolution (NFR-21), so two links created in the
        # same second would otherwise tie; `id` breaks the tie deterministically.
        order_by: [desc: l.inserted_at, desc: l.id],
        preload: [:issuing_user, :target_user]
    )
  end

  @doc """
  AUTH-07: revokes `link` at `now`, as long as it has not already been used. Revoking an
  already-used or already-revoked link is refused (distinctly) rather than silently
  accepted — the caller decides what, if anything, to tell the user.
  """
  @spec revoke(EnrollmentLink.t(), DateTime.t()) ::
          {:ok, EnrollmentLink.t()} | {:error, :already_used | :already_revoked}
  def revoke(%EnrollmentLink{used_at: %DateTime{}}, _now), do: {:error, :already_used}
  def revoke(%EnrollmentLink{revoked_at: %DateTime{}}, _now), do: {:error, :already_revoked}

  def revoke(%EnrollmentLink{} = link, now) do
    link |> EnrollmentLink.revoke_changeset(now) |> Repo.update()
  end

  @doc """
  Looks `token` up and reports whether it can be redeemed right now (AUTH-06): a used,
  expired or revoked link is rejected with a specific reason rather than a generic
  failure, so the landing page can show a clear one — without exposing anything else
  about the link, per AUTH-01 (public only for a *valid* link).

  On success, the link is preloaded with `:issuing_user` and `:target_user`.
  """
  @spec fetch_for_redemption(String.t(), DateTime.t()) ::
          {:ok, EnrollmentLink.t()} | {:error, redemption_error()}
  def fetch_for_redemption(token, now \\ DateTime.utc_now()) when is_binary(token) do
    case Repo.get_by(EnrollmentLink, token: token) do
      nil -> {:error, :not_found}
      %EnrollmentLink{used_at: %DateTime{}} -> {:error, :used}
      %EnrollmentLink{revoked_at: %DateTime{}} -> {:error, :revoked}
      %EnrollmentLink{} = link -> validate_expiry(link, now)
    end
  end

  defp validate_expiry(link, now) do
    if DateTime.compare(link.expires_at, now) == :gt do
      {:ok, Repo.preload(link, [:issuing_user, :target_user])}
    else
      {:error, :expired}
    end
  end

  @doc """
  Atomically marks `link` used at `now` — the single point where a link actually becomes
  single-use (see the moduledoc). Returns `:ok` for the caller that wins the race,
  `:error` for every other caller — including one racing against `revoke/2`, since the
  same `WHERE` clause guards both `used_at` and `revoked_at`.
  """
  @spec claim(EnrollmentLink.t(), DateTime.t()) :: :ok | :error
  def claim(%EnrollmentLink{id: id}, now) do
    {count, _} =
      Repo.update_all(
        from(l in EnrollmentLink,
          where:
            l.id == ^id and is_nil(l.used_at) and is_nil(l.revoked_at) and l.expires_at > ^now
        ),
        set: [used_at: now, updated_at: now]
      )

    if count == 1, do: :ok, else: :error
  end

  @doc "AUTH-05: records the newly created user as `link`'s target once it is redeemed."
  @spec assign_target_user(EnrollmentLink.t(), User.t()) ::
          {:ok, EnrollmentLink.t()} | {:error, Ecto.Changeset.t()}
  def assign_target_user(%EnrollmentLink{} = link, %User{} = user) do
    link |> EnrollmentLink.assign_target_user_changeset(user) |> Repo.update()
  end

  @doc "A short, user-facing label for `link`'s flavour, e.g. for log descriptions and cards."
  @spec flavour_label(EnrollmentLink.t()) :: String.t()
  def flavour_label(%EnrollmentLink{flavour: "device"}), do: "device"
  def flavour_label(%EnrollmentLink{flavour: "user_invitation"}), do: "invitation"
  def flavour_label(%EnrollmentLink{flavour: "recovery"}), do: "recovery"
end
